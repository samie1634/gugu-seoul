#!/usr/bin/python3
"""Local, derived visual elevation overlay. Never rewrites source OSM observations.
4 m headwater drop is documented by Seoul Facilities Corporation. All channel
absolute elevations, promenade offsets and pool dimensions are artistic estimates.
"""
import json, pathlib, math
from osgeo import ogr
R=pathlib.Path(__file__).resolve().parents[1]
D=R/'src/native/ported/map/real-map'
def read(p): return json.loads(p.read_text().split(' = ',1)[1].strip().removesuffix(';'))
def poly(r): return ogr.CreateGeometryFromJson(json.dumps({'type':'Polygon','coordinates':r}))
def parts(g):
 if g.IsEmpty(): return
 if g.GetGeometryName()=='POLYGON': yield g.Clone()
 elif g.GetGeometryName() in ('MULTIPOLYGON','GEOMETRYCOLLECTION'):
  for i in range(g.GetGeometryCount()): yield from parts(g.GetGeometryRef(i))
def union(gs):
 c=ogr.Geometry(ogr.wkbMultiPolygon)
 for g in gs:
  for p in parts(g): c.AddGeometry(p)
 return c.UnionCascaded() if c.GetGeometryCount() else c
def rings(g): return json.loads(g.ExportToJson())['coordinates']
O=(-172.363,425.259); dx,dz=.9953,.0969
L=math.hypot(dx,dz); dx/=L;dz/=L
def at(u,v): return [O[0]+u*dx-v*dz,O[1]+u*dz+v*dx]
def rect(u0,u1,v0,v1): return poly([[at(u0,v0),at(u1,v0),at(u1,v1),at(u0,v1),at(u0,v0)]])
data=read(D/'data.ts'); old=read(D/'surfaces.ts')
water=union([poly(w['rings']) for w in data['water']]); bounds=poly([[[-574.4,-555.1],[574.4,-555.1],[574.4,555.1],[-574.4,555.1],[-574.4,-555.1]]])
head=union([rect(-8,1,-10.4,10.4),rect(-28,-8,-7.25,7.25)])
exc=union([water.Buffer(3,1),head]).Intersection(bounds)
# Do not cut any existing building's foundation, even at an estimated bank edge.
bs=union([poly(b['rings']) for b in data['buildings']])
exc=exc.Difference(bs)
terrace=exc.Difference(water).Difference(rect(-28,0,-7.5,7.5))
def bridge_rect(cx,cz,width,span,angle):
 c,s=math.cos(angle),math.sin(angle)
 return poly([[[cx+u*c-v*s,cz+u*s+v*c] for u,v in [(-width/2,-span/2),(width/2,-span/2),(width/2,span/2),(-width/2,span/2),(-width/2,-span/2)]]])
bridge_decks=union([bridge_rect(-106.53,428.1205,27.5,19.5,math.atan2(1.410,24.295)),bridge_rect(47.318,443.253,14.4,23.8,math.atan2(1.322,26.904))]+[poly(r['rings']) for r in data['roads'] if r['bridge'] and not r['underground'] and min(p[1] for p in r['rings'][0])>400])
cut_mask=union([exc,bridge_decks])
replacements=[]
for i,s in enumerate(old):
 if s['kind']=='water': continue
 g=poly(s['rings'])
 mask=bridge_decks if s['kind']=='bridge' else cut_mask
 if not g.Intersects(mask): continue
 cut=g.Difference(mask)
 replacements.append({'index':i,'pieces':[rings(p) for p in parts(cut) if p.GetArea()>1e-8]})
out={'origin':list(O),'direction':[dx,dz], 'water':[rings(p) for p in parts(water)],'excavation':[rings(p) for p in parts(exc)],'terraces':[rings(p) for p in parts(terrace)],'replacements':replacements,'sourceWaterArea':water.GetArea(),'excavationArea':exc.GetArea()}
(D/'cheonggye-channel-data.ts').write_text('// Generated by tools/prepare-cheonggye-channel.py. Derived ODbL geometry. Not a survey.\nexport const cheonggyeChannelData = '+json.dumps(out,separators=(',',':'))+';\n')
print(json.dumps({'replacedSurfaceCount':len(replacements),'waterArea':water.GetArea(),'excavationArea':exc.GetArea(),'valid':exc.IsValid()}))
