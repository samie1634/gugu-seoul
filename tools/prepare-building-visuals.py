"""Offline renderer-only LOD and colour metadata; does not change the source dataset."""
import json,pathlib,collections
from osgeo import ogr
root=pathlib.Path(__file__).resolve().parents[1]
source=json.loads((root/'public/data/seoul-osm.json').read_text())
features={f['id']:f for f in source['runtime']['features']}
models={};color_count=collections.Counter();original=0;simplified=0
for b in source['render_adapter']['buildings']:
 g=ogr.CreateGeometryFromJson(json.dumps({'type':'Polygon','coordinates':b['rings']}))
 simple=g.SimplifyPreserveTopology(1.2)
 if simple.IsEmpty() or not simple.IsValid() or simple.GetGeometryName()!='POLYGON':simple=g
 # Retain holes and component topology, heights and absolute position.
 rings=json.loads(simple.ExportToJson())['coordinates']
 if len(rings)!=len(b['rings']):rings=b['rings']
 original+=sum(len(r)-1 for r in b['rings']);simplified+=sum(len(r)-1 for r in rings)
 tags=features[b['sourceId']]['tags'];wall=tags.get('building:colour');roof=tags.get('roof:colour')
 if wall:color_count['wall_tag']+=1
 if roof:color_count['roof_tag']+=1
 models[b['id']]={'rings':rings,'wallColor':wall,'roofColor':roof,'colorStatus':'osm_tag_unverified' if wall or roof else 'illustrative_palette_not_measured'}
header="// Generated by tools/prepare-building-visuals.py. OSM contributors, ODbL-1.0.\n// Geometry simplification only; original source/collision geometry and heights remain unchanged.\n"
(root/'src/native/ported/map/real-map/visual-data.ts').write_text(header+"export const buildingVisuals: Record<string,{rings:number[][][];wallColor:string|null;roofColor:string|null;colorStatus:string}> = "+json.dumps(models,ensure_ascii=False,separators=(',',':'))+';\n')
(root/'public/data/seoul-building-visuals.json').write_text(json.dumps({'license':'ODbL-1.0','attribution':'© OpenStreetMap contributors','source_database':'seoul-osm.json','simplification_tolerance_m':1.2,'colors':'OSM colour tags are unverified; missing colours use an illustrative runtime palette, not measured colours.','buildings':models},ensure_ascii=False,separators=(',',':')))
print(json.dumps({'original_ring_vertices':original,'far_ring_vertices':simplified,'colors':color_count},indent=2))
